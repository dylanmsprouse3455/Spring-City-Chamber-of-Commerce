/* B1 - DOM ROOM */
const memberList = document.getElementById("member-list");
const memberSearch = document.getElementById("member-search");
const memberCount = document.getElementById("member-count");
const emptyState = document.getElementById("empty-state");
const filterButtons = Array.from(document.querySelectorAll(".filter-chip"));
const sortToggle = document.getElementById("sort-toggle");
const sortLabel = document.getElementById("sort-label");

/* B2 - STATE ROOM */
let activeFilter = "all";
let sortDirection = "az";

/* C1 - HELPERS */
function cleanPhone(member) {
  return member.phone || "";
}

function displayPhone(member) {
  return member.displayPhone || member.phone || "";
}

function googleMapUrl(address) {
  return `https://maps.google.com/?q=${encodeURIComponent(address)}`;
}

function escapeHTML(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function memberSearchText(member) {
  return [
    member.name,
    member.category,
    member.categoryLabel,
    member.description,
    member.address,
    member.phone,
    member.displayPhone,
    member.email,
    member.website,
    member.contact,
    member.details
  ]
    .join(" ")
    .toLowerCase();
}

/* D1 - FILTER ROOM */
function getFilteredMembers() {
  const query = memberSearch.value.toLowerCase().trim();

  let list = MEMBERS.filter((member) => {
    const label = String(member.categoryLabel || "").toLowerCase();
    const category = String(member.category || "").toLowerCase();

    const matchesSearch = memberSearchText(member).includes(query);
    const matchesFilter =
      activeFilter === "all" ||
      category === activeFilter ||
      label === activeFilter ||
      (activeFilter === "business" &&
        ["business", "banking", "finance", "real estate", "manufacturing", "market", "retail"].includes(label)) ||
      (activeFilter === "services" &&
        ["services", "insurance", "construction", "plumbing", "electrical", "utility", "salon", "cleaning", "appraisal", "storage"].includes(label)) ||
      (activeFilter === "health" &&
        ["health", "dental", "pharmacy", "optical", "senior care", "rehab", "emergency"].includes(label)) ||
      (activeFilter === "dining" &&
        ["dining", "restaurant", "market"].includes(label));

    return matchesSearch && matchesFilter;
  });

  list.sort((a, b) => {
    const first = a.name.toLowerCase();
    const second = b.name.toLowerCase();

    if (sortDirection === "az") {
      return first.localeCompare(second);
    }

    return second.localeCompare(first);
  });

  return list;
}

/* E1 - CARD BUILDER */
function createMemberCard(member, index) {
  const phone = cleanPhone(member);
  const phoneText = displayPhone(member);
  const hasAddress = Boolean(member.address);
  const hasPhone = Boolean(phone);
  const hasEmail = Boolean(member.email);
  const hasWebsite = Boolean(member.website);
  const hasContact = Boolean(member.contact);
  const hasDetails = Boolean(member.details);
  const hasExtraPhones = Array.isArray(member.extraPhones) && member.extraPhones.length > 0;

  const extraPhoneRows = hasExtraPhones
    ? member.extraPhones
        .map((item) => {
          return `
            <div class="detail-row">
              <i class="fa-solid fa-phone"></i>
              <a href="tel:${escapeHTML(item.phone)}">${escapeHTML(item.label)}: ${escapeHTML(item.displayPhone)}</a>
            </div>
          `;
        })
        .join("")
    : "";

  const detailRows = `
    ${
      hasAddress
        ? `
          <div class="detail-row">
            <i class="fa-solid fa-location-dot"></i>
            <span>${escapeHTML(member.address)}</span>
          </div>
        `
        : ""
    }

    ${
      hasPhone
        ? `
          <div class="detail-row">
            <i class="fa-solid fa-phone"></i>
            <a href="tel:${escapeHTML(phone)}">${escapeHTML(phoneText)}</a>
          </div>
        `
        : ""
    }

    ${extraPhoneRows}

    ${
      hasEmail
        ? `
          <div class="detail-row">
            <i class="fa-solid fa-envelope"></i>
            <a href="mailto:${escapeHTML(member.email)}">${escapeHTML(member.email)}</a>
          </div>
        `
        : ""
    }

    ${
      hasWebsite
        ? `
          <div class="detail-row">
            <i class="fa-solid fa-globe"></i>
            <a href="${escapeHTML(member.website)}">${escapeHTML(member.website)}</a>
          </div>
        `
        : ""
    }

    ${
      hasContact
        ? `
          <div class="detail-row">
            <i class="fa-solid fa-user"></i>
            <span>${escapeHTML(member.contact)}</span>
          </div>
        `
        : ""
    }

    ${
      hasDetails
        ? `
          <div class="detail-row">
            <i class="fa-solid fa-note-sticky"></i>
            <span>${escapeHTML(member.details)}</span>
          </div>
        `
        : ""
    }

    <div class="detail-row">
      <i class="fa-solid fa-circle-info"></i>
      <span>${escapeHTML(member.description)}</span>
    </div>
  `;

  const actionButtons = `
    <div class="member-actions">
      ${
        hasPhone
          ? `
            <a class="small-action" href="tel:${escapeHTML(phone)}">
              <i class="fa-solid fa-phone"></i>
              Call
            </a>
          `
          : `
            <a class="small-action muted-action" href="./contact-5.html">
              <i class="fa-solid fa-phone"></i>
              Contact
            </a>
          `
      }

      ${
        hasAddress
          ? `
            <a class="small-action" href="${googleMapUrl(member.address)}">
              <i class="fa-solid fa-location-dot"></i>
              Map
            </a>
          `
          : `
            <a class="small-action muted-action" href="./membershipdirectory.html">
              <i class="fa-solid fa-location-dot"></i>
              Info
            </a>
          `
      }

      ${
        hasWebsite
          ? `
            <a class="small-action" href="${escapeHTML(member.website)}">
              <i class="fa-solid fa-globe"></i>
              Website
            </a>
          `
          : `
            <a class="small-action" href="${escapeHTML(member.detailsUrl || "./membershipdirectory.html")}">
              <i class="fa-solid fa-link"></i>
              Details
            </a>
          `
      }
    </div>
  `;

  return `
    <details class="member-card" ${index === 0 ? "open" : ""}>
      <summary>
        <span class="member-name">${escapeHTML(member.name)}</span>
        <span class="member-category">${escapeHTML(member.categoryLabel)}</span>
        <i class="fa-solid fa-chevron-down caret"></i>
      </summary>

      <div class="member-detail">
        <div class="detail-panel">
          ${detailRows}
          ${actionButtons}
        </div>
      </div>
    </details>
  `;
}

/* F1 - RENDER ROOM */
function renderMembers() {
  const filtered = getFilteredMembers();

  memberList.innerHTML = filtered
    .map((member, index) => createMemberCard(member, index))
    .join("");

  memberCount.textContent =
    filtered.length === 1
      ? "Showing 1 member"
      : `Showing ${filtered.length} members`;

  emptyState.hidden = filtered.length !== 0;
}

/* G1 - EVENT ROOM */
memberSearch.addEventListener("input", renderMembers);

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    activeFilter = button.dataset.filter;

    filterButtons.forEach((btn) => btn.classList.remove("active"));
    button.classList.add("active");

    renderMembers();
  });
});

sortToggle.addEventListener("click", () => {
  sortDirection = sortDirection === "az" ? "za" : "az";
  sortLabel.textContent = sortDirection === "az" ? "Sort: A-Z" : "Sort: Z-A";
  renderMembers();
});

/* H1 - INIT */
renderMembers();